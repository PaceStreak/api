/**
 * Writes src/db/fk-users.gen.ts: every (table, column) with a foreign key to users.id, from the Drizzle schema.
 * Account merge and purge iterate this list instead of introspecting the catalog at runtime. A schema test asserts
 * it equals what D1 reports through pragma_foreign_key_list. Run after any schema change: `pnpm db:fk-users`.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { getTableName, is } from "drizzle-orm";
import { toSnakeCase } from "drizzle-orm/casing";
import { getTableConfig, SQLiteTable } from "drizzle-orm/sqlite-core";
import * as schema from "../src/db/schema/index.ts";

type Row = { table: string; column: string; onDelete: string };
const rows: Row[] = [];
for (const value of Object.values(schema)) {
  if (!is(value, SQLiteTable)) continue;
  const cfg = getTableConfig(value);
  for (const fk of cfg.foreignKeys) {
    const ref = fk.reference();
    if (getTableName(ref.foreignTable) !== "users") continue;
    for (const col of ref.columns) {
      const name = col.keyAsName ? toSnakeCase(col.name) : col.name;
      rows.push({ table: cfg.name, column: name, onDelete: fk.onDelete ?? "no action" });
    }
  }
}
rows.sort((a, b) => a.table.localeCompare(b.table) || a.column.localeCompare(b.column));

const body = rows
  .map((r) => `  { table: "${r.table}", column: "${r.column}", onDelete: "${r.onDelete}" },`)
  .join("\n");
const out = `// Generated by scripts/gen-fk-users.ts from src/db/schema. Do not edit; run \`pnpm db:fk-users\`.
export interface UserForeignKey {
  readonly table: string;
  readonly column: string;
  readonly onDelete: "cascade" | "set null" | "no action" | "restrict" | "set default";
}

export const FK_USERS: readonly UserForeignKey[] = [
${body}
];
`;
writeFileSync(path.join(import.meta.dirname, "../src/db/fk-users.gen.ts"), out);
console.log(`fk-users: ${rows.length} columns`);
