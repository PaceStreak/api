"""The built-in catalogue: disciplines, muscles, exercises and starter routines.

Everything here is PaceStreak's own writing. The predecessor project shipped a
third-party paid program's exercise text; none of it is reproduced here, and
none should be added - this repository is AGPL, so whatever lands here is
published.

The library lives in code rather than in tables because it is versioned with
the code that interprets it: an exercise id is a stable slug that logged sets
refer to forever, and a migration to "add a row" is ceremony for no benefit.
Users add their own movements as custom exercises, which *are* rows.
"""

