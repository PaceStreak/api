# How load is entered. `weight` is external load; `bodyweight` logs reps only;
# `weighted_bw` is added load on a bodyweight movement; `time` logs a hold.
LOAD_TYPES = ("weight", "bodyweight", "weighted_bw", "time")


@dataclass(frozen=True)
class Exercise:
    id: str
    name: str
    pattern: str
    equipment: str
    primary: tuple[str, ...]
    secondary: tuple[str, ...] = ()
    load_type: str = "weight"
    rest_sec: int = 120
    cue: str = ""
    unilateral: bool = False
    aliases: tuple[str, ...] = field(default=())

    def to_dict(self) -> dict:
        data = asdict(self)
        data["custom"] = False
        return data


def _x(*args, **kwargs) -> Exercise:
    return Exercise(*args, **kwargs)


